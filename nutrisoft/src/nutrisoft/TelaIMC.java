    private void BtCalcActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtCalcActionPerformed
        
        // Verifica se os campos estão preenchidos
        if (Altura.getText().trim().isEmpty() || Peso.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, preencha todos os campos.");
            return;
        }

        double altura;
        double peso;

        // Converte os textos em números (aceita vírgula ou ponto)
        try {
            altura = Double.parseDouble(TxAltura.getText().trim().replace(",", "."));
            peso = Double.parseDouble(TxPeso.getText().trim().replace(",", "."));
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Digite apenas números válidos. Exemplo: 1.70 e 65");
            return;
        }

        // Valores precisam ser positivos
        if (altura <= 0 || peso <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Altura e peso devem ser maiores que zero.");
            return;
        }

        // Cálculo do IMC
        double imc = peso / (altura * altura);

        // Interpretação
        String interpretacao;
        if (imc < 18.5) {
            interpretacao = "Magreza";
        } else if (imc < 25) {
            interpretacao = "Normal";
        } else if (imc < 30) {
            interpretacao = "Sobrepeso";
        } else if (imc < 40) {
            interpretacao = "Obesidade";
        } else {
            interpretacao = "Obesidade grave";
        }

        // Mostra nas labels
        LbResultado.setText("Resultado: " + String.format("%.1f", imc));
        LbInterp.setText("Interpretação: " + interpretacao);
    }//GEN-LAST:event_BtCalcActionPerformed

