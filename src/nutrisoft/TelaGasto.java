    private void BtCalcActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtCalcActionPerformed
                                         
    // 1. Validar se os campos de texto estão preenchidos
    if (TxPeso.getText().trim().isEmpty() || TxAltura.getText().trim().isEmpty() || TxIdade.getText().trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, preencha todos os campos.", "Atenção", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 2. Validar se o sexo foi selecionado
    if (!RbHomem.isSelected() && !RbMulher.isSelected()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, selecione o sexo (Homem ou Mulher).", "Atenção", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    double peso, altura;
    int idade;

    // 3. Conversão segura de tipos (evita que o programa quebre com letras ou pontos/vírgulas erradas)
    try {
        peso = Double.parseDouble(TxPeso.getText().trim().replace(",", "."));
        altura = Double.parseDouble(TxAltura.getText().trim().replace(",", "."));
        idade = Integer.parseInt(TxIdade.getText().trim());
    } catch (NumberFormatException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Digite apenas números válidos nos campos numéricos.", "Erro de Formato", javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }

    // 4. Validação de valores maiores que zero
    if (peso <= 0 || altura <= 0 || idade <= 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Os valores informados devem ser maiores que zero.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }

    // 5. Cálculo do Gasto Calórico Basal (conforme as fórmulas do enunciado)
    double calBasal = 0;
    if (RbHomem.isSelected()) {
        // Homem: CalBasal = 66 + (13,8 * Peso) + (5 * Altura) – (6,8 * Idade)
        calBasal = 66 + (13.8 * peso) + (5 * altura) - (6.8 * idade);
    } else {
        // Mulher: CalBasal = 655 + (9,6 * Peso) + (1,9 * Altura) – (4,7 * Idade)
        calBasal = 655 + (9.6 * peso) + (1.9 * altura) - (4.7 * idade);
    }

    // 6. Cálculo do Gasto Total baseado no nível de atividade selecionado na ComboBox
    int indiceAtividade = CmbAtividade.getSelectedIndex();
    double fatorAtividade = 1.2; // padrão

    switch (indiceAtividade) {
        case 0: // Sedentário
            fatorAtividade = 1.2;
            break;
        case 1: // Leve (1 a 3 dias/semana)
            fatorAtividade = 1.375;
            break;
        case 2: // Moderado (3 a 5 dias/semana)
            fatorAtividade = 1.55;
            break;
        case 3: // Ativo (5 a 6 dias/semana)
            fatorAtividade = 1.725;
            break;
        case 4: // Extremamente ativo (diário)
            fatorAtividade = 1.9;
            break;
        default:
            fatorAtividade = 1.2;
            break;
    }

    double calTotal = calBasal * fatorAtividade;

    // 7. Exibir os resultados nos labels da tela
    LbBasal.setText(String.format("Gasto Basal: %.2f kcal", calBasal));
    LbTotal.setText(String.format("Gasto Total: %.2f kcal", calTotal));
    }//GEN-LAST:event_BtCalcActionPerformed

