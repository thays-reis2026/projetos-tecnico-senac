    private void btnFinalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFinalizarActionPerformed
        try {
            String texto = txtReceita.getText().trim();
            if (texto.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Digite a receita/observações para finalizar.");
                return;
            }
            consulta.setReceita(texto);
            consulta.setRealizada(true);
            dispose();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao finalizar: " + e.getMessage());
        }   
    }//GEN-LAST:event_btnFinalizarActionPerformed

