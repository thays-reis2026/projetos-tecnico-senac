    private void btnFinalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFinalizarActionPerformed
        int linha = tabela.getSelectedRow();
        if (linha < 0) {
            JOptionPane.showMessageDialog(this, "Selecione uma consulta na tabela.");
            return;
        }
        TelaDetalhes d = new TelaDetalhes(this, true);
        d.setConsulta(ConsultaRepositorio.listar().get(linha));
        d.setLocationRelativeTo(this);
        d.setVisible(true);
        atualizarTabela();
    }//GEN-LAST:event_btnFinalizarActionPerformed

    private void atualizarTabela() {
        DefaultTableModel m = (DefaultTableModel) tabela.getModel();
        m.setRowCount(0);
        for (Consulta c : ConsultaRepositorio.listar()) {
            m.addRow(new Object[]{
                c.getNome(), c.getCpf(), c.getTelefone(), c.getData(),
                c.isJaEraPaciente() ? "sim" : "não",
                c.isRealizada() ? "sim" : "não"
        });
    }
}
    private void btnNovaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNovaActionPerformed
        TelaCadastro t = new TelaCadastro(this, true);
        t.setLocationRelativeTo(this);
        t.setVisible(true);   // trava aqui até a janela fechar
        atualizarTabela();
    }//GEN-LAST:event_btnNovaActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tabela.getSelectedRow();
        if (linha < 0) {
            JOptionPane.showMessageDialog(this, "Selecione uma consulta na tabela.");
            return;
        }
        try {
            ConsultaRepositorio.remover(linha);
            atualizarTabela();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao excluir: " + e.getMessage());
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

