    private void BtCalcActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtCalcActionPerformed
                                       
    // 1. Validação de campo vazio
    if (TxCalorias.getText().trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, preencha o campo de calorias.", "Atenção", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    double calorias;

    // 2. Conversão segura de formato
    try {
        calorias = Double.parseDouble(TxCalorias.getText().trim().replace(",", "."));
    } catch (NumberFormatException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Digite apenas um número válido para as calorias.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }

    // 3. Validação de valor positivo
    if (calorias <= 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "A quantidade de calorias deve ser maior que zero.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }

    // 4. Fórmulas de Recomendações de Nutrientes (em gramas)
    // Carboidratos = calorias * 0,5 / 4
    double carboidratos = (calorias * 0.5) / 4;
    
    // Proteínas = calorias * 0,25 / 4
    double proteinas = (calorias * 0.25) / 4;
    
    // Gordura = calorias * 0,25 / 9
    double gordura = (calorias * 0.25) / 9;

    // 5. Exibir nos labels
    LbCarb.setText(String.format("Carboidratos: %.2f g", carboidratos));
    LbProt.setText(String.format("Proteínas: %.2f g", proteinas));
    LbGord.setText(String.format("Gordura: %.2f g", gordura));
    }//GEN-LAST:event_BtCalcActionPerformed

